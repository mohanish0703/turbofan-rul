"""Collect run records into one comparison: <results>/metrics.md and <results>/metrics.json.

python -m rul.report                          # real runs in results/runs/
python -m rul.report --results results/smoke  # SYNTHETIC smoke runs

The selected model per dataset is the one with the lowest CV RMSE. Test-set numbers are
reported but never used to choose between models.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from rul.data import DATASETS
from rul.models import MODEL_NAMES
from rul.train import RESULTS_DIR

# Settings that must match across runs of one dataset for the table to compare like with like.
_SHARED = (("preprocess", "rul_cap"), ("preprocess", "window_length"), ("cv", "n_folds"))


def load_runs(runs_dir: str | Path) -> list[dict[str, Any]]:
    paths = sorted(Path(runs_dir).glob("*.json"))
    if not paths:
        raise FileNotFoundError(f"No run records in {runs_dir}; run `python -m rul.train` first")
    runs = []
    for path in paths:
        with open(path, encoding="utf-8") as f:
            runs.append(json.load(f))
    if len({r["synthetic"] for r in runs}) > 1:
        raise ValueError(f"{runs_dir} mixes SYNTHETIC and real runs; keep them apart")
    return runs


def _sort_key(run: dict[str, Any]) -> tuple[int, int, str]:
    model = run["model"]
    order = MODEL_NAMES.index(model) if model in MODEL_NAMES else len(MODEL_NAMES)
    return DATASETS.index(run["dataset"]), order, model


def summary_rows(runs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = []
    for run in sorted(runs, key=_sort_key):
        cv, test = run["cv"]["summary"], run["test"]
        rows.append(
            {
                "dataset": run["dataset"],
                "model": run["model"],
                "cv_rmse_mean": cv["rmse"]["mean"],
                "cv_rmse_std": cv["rmse"]["std"],
                "cv_mae_mean": cv["mae"]["mean"],
                "test_rmse": test["metrics"]["rmse"],
                "test_mae": test["metrics"]["mae"],
                "test_nasa_score": test["metrics"]["nasa_score"],
                "test_rmse_capped_truth": test["metrics_capped_truth"]["rmse"],
                "selected": False,
                "git_commit": run["code_version"].get("git_commit"),
                "git_dirty": run["code_version"].get("git_dirty"),
            }
        )
    for ds in {r["dataset"] for r in rows}:
        best = min((r for r in rows if r["dataset"] == ds), key=lambda r: r["cv_rmse_mean"])
        best["selected"] = True
    return rows


def _dataset_settings(runs: list[dict[str, Any]], dataset: str) -> dict[str, Any]:
    ds_runs = [r for r in runs if r["dataset"] == dataset]
    settings = {f"{a}.{b}": ds_runs[0]["config"][a][b] for a, b in _SHARED}
    for run in ds_runs[1:]:
        other = {f"{a}.{b}": run["config"][a][b] for a, b in _SHARED}
        if other != settings:
            raise ValueError(
                f"{dataset} runs use different settings ({settings} vs {other} for "
                f"{run['model']}); rerun them with one config so the table is comparable"
            )
    settings["train_engines"] = ds_runs[0]["train_engines"]
    settings["test_engines"] = ds_runs[0]["test"]["engines"]
    return settings


def _score(value: float) -> str:
    return f"{value:,.1f}" if value < 1000 else f"{value:,.0f}"


def render_markdown(runs: list[dict[str, Any]], rows: list[dict[str, Any]], source: str) -> str:
    synthetic = runs[0]["synthetic"]
    datasets = [ds for ds in DATASETS if any(r["dataset"] == ds for r in rows)]
    models = list(dict.fromkeys(r["model"] for r in rows))
    lines = ["# Results", ""]
    if synthetic:
        lines += [
            "> **SYNTHETIC DATA.** These runs use generated stand-in files, not NASA C-MAPSS.",
            "> The numbers only show that the pipeline runs; they say nothing about model quality.",
            "",
        ]
    lines += [
        f"Generated by `python -m rul.report` from {len(runs)} run records in `{source}`. "
        "Do not edit by hand.",
        "",
        "- **Test**: official protocol. Each model is refit on all training engines and predicts "
        "RUL from the last window of every test engine; truth is `RUL_FDxxx.txt`, not capped.",
        "- **Test RMSE (capped truth)**: the same predictions against the true RUL capped at the "
        "training cap, as some papers report it. Labelled extra, not the headline number.",
        "- **CV**: GroupKFold by engine on the training set, preprocessing refit in every fold; "
        "every window of the held-out engines against the capped target; mean +/- std over folds.",
        "- **Selected**: lowest CV RMSE per dataset. Test results play no part in the choice.",
        "- **Models**: `naive` predicts the mean training target; the others regress on per-sensor "
        "window statistics (last, mean, std, slope) plus the cycle number. Hyperparameters are "
        "hand-set defaults, not tuned.",
        "",
        "## Test RMSE by dataset",
        "",
        "| Model | " + " | ".join(datasets) + " |",
        "|---|" + "---|" * len(datasets),
    ]
    by_key = {(r["dataset"], r["model"]): r for r in rows}
    for model in models:
        cells = []
        for ds in datasets:
            row = by_key.get((ds, model))
            cells.append("-" if row is None else f"{row['test_rmse']:.2f}")
        lines.append(f"| {model} | " + " | ".join(cells) + " |")

    for ds in datasets:
        s = _dataset_settings(runs, ds)
        lines += [
            "",
            f"## {ds}",
            "",
            f"{s['train_engines']} training / {s['test_engines']} test engines, "
            f"{s['cv.n_folds']} CV folds, RUL cap {s['preprocess.rul_cap']}, "
            f"window {s['preprocess.window_length']} cycles.",
            "",
            "| Model | CV RMSE | CV MAE | Test RMSE | Test MAE | Test NASA score "
            "| Test RMSE (capped truth) |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in (r for r in rows if r["dataset"] == ds):
            name = f"**{r['model']}** (selected)" if r["selected"] else r["model"]
            lines.append(
                f"| {name} | {r['cv_rmse_mean']:.2f} +/- {r['cv_rmse_std']:.2f} "
                f"| {r['cv_mae_mean']:.2f} | {r['test_rmse']:.2f} | {r['test_mae']:.2f} "
                f"| {_score(r['test_nasa_score'])} | {r['test_rmse_capped_truth']:.2f} |"
            )

    commits = {f"{str(r['git_commit'])[:7]}{' (dirty)' if r['git_dirty'] else ''}" for r in rows}
    lines += ["", f"Code version of these runs: {', '.join(sorted(commits))}.", ""]
    return "\n".join(lines)


def write_report(results_dir: str | Path) -> tuple[Path, Path]:
    results_dir = Path(results_dir)
    runs_dir = results_dir / "runs"
    runs = load_runs(runs_dir)
    if runs[0]["synthetic"] and results_dir.resolve() == RESULTS_DIR.resolve():
        raise ValueError("Refusing to write a SYNTHETIC report into results/; use results/smoke/")
    rows = summary_rows(runs)

    md_path, json_path = results_dir / "metrics.md", results_dir / "metrics.json"
    md_path.write_text(
        render_markdown(runs, rows, runs_dir.as_posix() + "/"), encoding="utf-8", newline="\n"
    )
    payload = {"synthetic": runs[0]["synthetic"], "source": runs_dir.as_posix(), "rows": rows}
    with open(json_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(payload, f, indent=2)
        f.write("\n")
    return md_path, json_path


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", default=str(RESULTS_DIR), help="dir containing runs/")
    args = parser.parse_args(argv)
    md_path, json_path = write_report(args.results)
    print(f"Wrote {md_path} and {json_path}")


if __name__ == "__main__":
    main()
